def sqNum(num: int) -> int:
    """Square numbers
    
       :params num: int
       :return num: int
    """
    return num * num
def removeNegetiveFromList(iter: list) -> list:
    """Removes Negetive From List
    
       :param iter: list
       :return []: List
    """
    return [x for x in iter if x > 0]

